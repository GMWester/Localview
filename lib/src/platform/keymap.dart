final Map<int, List<int>> _byHid = {for (final r in _table) r[0]: r};

int _usage(int hid) => (hid >> 16) == 0x07 ? hid & 0xFFFF : (hid > 0xFFFF ? -1 : hid);

int? evdevFor(int hid) => _byHid[_usage(hid)]?[1];
int? winScanFor(int hid) => _byHid[_usage(hid)]?[2];
int? macKeyFor(int hid) => _byHid[_usage(hid)]?[3];

/// HID usages (low 16 bits) for modifier keys.
bool isShift(int hid) => _usage(hid) == 0xE1 || _usage(hid) == 0xE5;
bool isCtrl(int hid) => _usage(hid) == 0xE0 || _usage(hid) == 0xE4;
bool isAlt(int hid) => _usage(hid) == 0xE2 || _usage(hid) == 0xE6;
bool isMeta(int hid) => _usage(hid) == 0xE3 || _usage(hid) == 0xE7;
